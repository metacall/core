/// Tag generated once each time the loader is loaded, the loader is unloaded on
/// metacall_destroy so it changes between initializations (i.e: when forking)
static CRATE_NAME_TAG: sync::OnceLock<String> = sync::OnceLock::new();

/// Counter of the crates compiled since the loader was loaded
static CRATE_NAME_COUNTER: AtomicUsize = AtomicUsize::new(0);

/// Generates a unique crate name from a base name (file or script name). The libraries
/// are loaded by name (SONAME) when other crates link against them, so two crates with
/// the same name would resolve to the first one loaded. The crate name is the base name
/// sanitized, a tag generated per loader initialization (libraries that cannot be unloaded
/// survive to metacall_destroy) and a counter of the crates compiled in this initialization.
pub fn unique_crate_name(base: &str) -> String {
    let mut name: String = base
        .chars()
        .map(|c| if c.is_ascii_alphanumeric() { c } else { '_' })
        .collect();

    // Crate names cannot be empty nor start with a digit
    if name.is_empty() || name.starts_with(|c: char| c.is_ascii_digit()) {
        name.insert_str(0, "crate_");
    }

    let tag =
        CRATE_NAME_TAG.get_or_init(|| iter::repeat_with(fastrand::lowercase).take(5).collect());
    let counter = CRATE_NAME_COUNTER.fetch_add(1, Ordering::Relaxed);

    format!("{}_{}_{}", name, tag, counter)
}

/// Name of the library generated by rustc for a crate, rustc requires it to link against it
fn library_name(crate_name: &str) -> String {
    let name = CString::new(crate_name).expect("CString::new failed");

    // The buffer must fit the platform prefix and extension too, which are a few characters
    let mut buffer: Vec<c_char> = vec![0; crate_name.len() + 32];

    unsafe {
        dynlink_impl_get_name(name.as_ptr(), buffer.as_mut_ptr(), buffer.len());

        CStr::from_ptr(buffer.as_ptr())
            .to_string_lossy()
            .into_owned()
    }
}

impl Source {
    /// Base name used to generate the crate name of the source
    fn base_name(&self) -> String {
        let file_stem = |path: &PathBuf| {
            path.file_stem()
                .unwrap_or_else(|| panic!("Unable to get the file stem of {:?}", path))
                .to_string_lossy()
                .to_string()
        };

        match self {
            Source::File { path } => file_stem(path),
            Source::Memory { name, .. } => file_stem(&PathBuf::from(name)),
            Source::Package { path } => file_stem(path).trim_start_matches("lib").to_owned(),
        }
    }

    pub fn build(source: Source) -> SourceImpl {
        let crate_name = unique_crate_name(&source.base_name());

        Source::build_with_crate_name(source, crate_name)
    }

    pub fn build_with_crate_name(source: Source, crate_name: String) -> SourceImpl {
        let input_path = |dir: &PathBuf, name: &PathBuf| {
            let mut path = PathBuf::from(dir);
            path.push(name);
            path.clone()
        };

        let output_path = |dir: &PathBuf| dir.join(library_name(&crate_name));

        match source {
            Source::File { ref path } => {
                let dir = PathBuf::from(
                    path.clone()
                        .parent()
                        .unwrap_or_else(|| panic!("Unable to get the parent of {:?}", path)),
                );
                let name = PathBuf::from(
                    path.file_name()
                        .unwrap_or_else(|| panic!("Unable to get the parent of {:?}", path)),
                );
                let temp_dir = std::env::temp_dir();
                SourceImpl {
                    input: SourceInput(config::Input::File(path.clone())),
                    input_path: input_path(&dir, &name),
                    output: output_path(&temp_dir),
                    crate_name,
                    source,
                }
            }
            Source::Memory { ref name, ref code } => {
                let dir = std::env::temp_dir();
                let name_path = PathBuf::from(name.clone());

                SourceImpl {
                    input: SourceInput(config::Input::Str {
                        name: rustc_span::FileName::Custom(name.clone()),
                        input: code.clone(),
                    }),
                    input_path: input_path(&dir, &name_path),
                    output: output_path(&dir),
                    crate_name,
                    source,
                }
            }
            Source::Package { ref path } => {
                let dir = PathBuf::from(
                    path.clone()
                        .parent()
                        .unwrap_or_else(|| panic!("Unable to get the parent of {:?}", path)),
                );
                let name = PathBuf::from(
                    path.file_name()
                        .unwrap_or_else(|| panic!("Unable to get the filename of {:?}", path)),
                );
                let temp_dir = std::env::temp_dir();
                SourceImpl {
                    input: SourceInput(config::Input::File(path.clone())),
                    input_path: input_path(&dir, &name),
                    output: output_path(&temp_dir),
                    crate_name,
                    source,
                }
            }
        }
    }
}

fn toolchain_path(home: Option<String>, toolchain: Option<String>) -> Option<PathBuf> {
    home.and_then(|home| {
        toolchain.map(|toolchain| {
            let mut path = PathBuf::from(home);
            path.push("toolchains");
            path.push(toolchain);
            path
        })
    })
}

fn compiler_sys_root() -> Option<PathBuf> {
    // Get the sysroot, looking from most specific to this invocation to the least:
    // - runtime environment
    //    - SYSROOT
    //    - RUSTUP_HOME, MULTIRUST_HOME, RUSTUP_TOOLCHAIN, MULTIRUST_TOOLCHAIN
    // - sysroot from rustc in the path
    // - compile-time environment
    //    - SYSROOT
    //    - RUSTUP_HOME, MULTIRUST_HOME, RUSTUP_TOOLCHAIN, MULTIRUST_TOOLCHAIN
    std::env::var("SYSROOT")
        .ok()
        .map(PathBuf::from)
        .or_else(|| {
            let home = std::env::var("RUSTUP_HOME")
                .or_else(|_| std::env::var("MULTIRUST_HOME"))
                .ok();
            let toolchain = std::env::var("RUSTUP_TOOLCHAIN")
                .or_else(|_| std::env::var("MULTIRUST_TOOLCHAIN"))
                .ok();
            toolchain_path(home, toolchain)
        })
        .or_else(|| option_env!("SYSROOT").map(PathBuf::from))
        .or_else(|| {
            let home = option_env!("RUSTUP_HOME")
                .or(option_env!("MULTIRUST_HOME"))
                .map(ToString::to_string);
            let toolchain = option_env!("RUSTUP_TOOLCHAIN")
                .or(option_env!("MULTIRUST_TOOLCHAIN"))
                .map(ToString::to_string);
            toolchain_path(home, toolchain)
        })
}

fn compiler_source() -> Option<PathBuf> {
    match compiler_sys_root() {
        Some(sys_root) => {
            let mut path = sys_root;
            path.push("lib");
            path.push("rustlib");
            path.push("src");
            path.push("rust");

            if path.exists() {
                Some(path)
            } else {
                None
            }
        }
        _ => None,
    }
}

/// Sysroot used by the compiler, the explicit one if any, otherwise the one where librustc_driver is
fn sysroot() -> PathBuf {
    config::Sysroot::new(compiler_sys_root())
        .path()
        .to_path_buf()
}

/// Path of the standard library (libstd) of the sysroot used by the compiler
fn std_library_path() -> Result<PathBuf, String> {
    #[cfg(windows)]
    let (directory, prefix, suffix) = (sysroot().join("bin"), "std-", ".dll");
    #[cfg(target_os = "macos")]
    let (directory, prefix, suffix) = (
        sysroot()
            .join("lib")
            .join("rustlib")
            .join(config::host_tuple())
            .join("lib"),
        "libstd-",
        ".dylib",
    );
    #[cfg(all(unix, not(target_os = "macos")))]
    let (directory, prefix, suffix) = (
        sysroot()
            .join("lib")
            .join("rustlib")
            .join(config::host_tuple())
            .join("lib"),
        "libstd-",
        ".so",
    );

    std::fs::read_dir(&directory)
        .map_err(|error| format!("Unable to read the directory {:?}: {}", directory, error))?
        .filter_map(|entry| entry.ok().map(|entry| entry.path()))
        .find(|path| {
            path.file_name()
                .and_then(|name| name.to_str())
                .is_some_and(|name| name.starts_with(prefix) && name.ends_with(suffix))
        })
        .ok_or_else(|| format!("Unable to find the standard library in {:?}", directory))
}

/// Crates with shared linkage link the standard library dynamically and depend on it by name,
/// so it must be loaded before them. It is loaded once and never unloaded from the process,
/// dropping the library only releases the handle.
fn std_library_load() -> Result<(), String> {
    static STD_LIBRARY: sync::OnceLock<Result<(), String>> = sync::OnceLock::new();

    STD_LIBRARY
        .get_or_init(|| {
            DynlinkLibrary::load(
                &std_library_path()?,
                DYNLINK_FLAGS_BIND_LOCAL | DYNLINK_FLAGS_BIND_LAZY | DYNLINK_FLAGS_BIND_NODELETE,
            )
            .map(|_library| ())
        })
        .clone()
}

/// How a crate compiled by the loader links the standard library, it defines how the crate
/// is compiled and loaded:
///
/// - Static, crates without templates (and the wrappers of packages): compiled as cdylib with
///   the standard library linked in, the standard library is not preloaded and the library is
///   loaded with LOCAL | LAZY. Thread local destructors are registered by the standard library
///   linked in the crate, so the system keeps the crate loaded while a destructor is pending,
///   otherwise it can be unloaded.
///
/// - Shared, crates with templates: compiled as dylib with prefer_dynamic (shared standard
///   library), so the templates can be instantiated after load by compiling new crates against
///   it, sharing its state. The standard library is preloaded and the library is loaded with
///   LOCAL | LAZY | NODELETE. Thread local destructors are registered by the shared standard
///   library, so the system keeps the standard library loaded instead of the crate, if the crate
///   was unloaded a thread exiting after it would run a destructor that is not mapped anymore.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Linkage {
    Static,
    Shared,
}

// Define the opaque pointer (C type: dynlink)
type Dynlink = *mut std::ffi::c_void;
type DynlinkSymbolAddr = unsafe extern "C" fn();

// Define flags as constants (mimicking the C #define values)
const DYNLINK_FLAGS_BIND_LAZY: u32 = 0x01 << 1; // Lazy loading bind flag
const DYNLINK_FLAGS_BIND_LOCAL: u32 = 0x01 << 2; // Private visibility bind flag
const DYNLINK_FLAGS_BIND_NODELETE: u32 = 0x01 << 4; // The library is never unloaded from the process

// Flags not used by the loader
// const DYNLINK_FLAGS_BIND_NOW: u32 = 0x01 << 0;       // Inmediate loading bind flag
// const DYNLINK_FLAGS_BIND_GLOBAL: u32 = 0x01 << 3;    // Public visibility bind flag
// const DYNLINK_FLAGS_BIND_SELF: u32 = 0x01 << 16;     // Private flag for when loading the current process

// FFI declarations of the dynlink functions (C functions)
extern "C" {
    pub fn dynlink_load_absolute(path: *const c_char, flags: u32) -> Dynlink;
    pub fn dynlink_symbol(
        dynlink: Dynlink,
        symbol_name: *const c_char,
        symbol_address: *mut DynlinkSymbolAddr,
    ) -> i32;
    pub fn dynlink_unload(dynlink: Dynlink);
    pub fn dynlink_impl_get_name(name: *const c_char, destination: *mut c_char, size: usize);
}

#[derive(Debug)]
pub struct DynlinkLibrary {
    pub instance: Dynlink,
}

impl DynlinkLibrary {
    fn load(path: &Path, flags: u32) -> Result<DynlinkLibrary, String> {
        let c_path = CString::new(path.to_str().unwrap()).expect("CString::new failed");

        unsafe {
            let instance = dynlink_load_absolute(c_path.as_ptr(), flags);

            if instance.is_null() {
                Err("Failed to load library: ".to_owned() + path.to_str().unwrap())
            } else {
                Ok(DynlinkLibrary { instance })
            }
        }
    }

    pub fn symbol(&self, symbol_name: &str) -> Result<DynlinkSymbolAddr, String> {
        let c_symbol_name = CString::new(symbol_name).expect("CString::new failed");

        unsafe {
            let mut symbol_address = std::mem::MaybeUninit::<DynlinkSymbolAddr>::uninit();

            let result = dynlink_symbol(
                self.instance,
                c_symbol_name.as_ptr(),
                symbol_address.as_mut_ptr(),
            );
            if result == 0 {
                Ok(symbol_address.assume_init())
            } else {
                Err(format!("Failed to find symbol: {}", symbol_name))
            }
        }
    }
}

impl Drop for DynlinkLibrary {
    fn drop(&mut self) {
        unsafe {
            if !self.instance.is_null() {
                // Unload the dynamic library
                dynlink_unload(self.instance);

                // Set the instance to null for safety
                self.instance = std::ptr::null_mut();
            }
        }
    }
}

