    fn test_compile_generics() {
        run_test(|| {
            let result = compile(
                Source::build(Source::Memory {
                    name: String::from("generic_test.rs"),
                    code: String::from(
                        r#"
                pub fn add<T>(a: T, b: T) -> T {
                    a
                }

                pub fn normal(a: i32) -> i32 {
                    a
                }
                "#,
                    ),
                }),
                &[],
            );

            match result {
                Err(comp_err) => {
                    assert!(false, "compilation failed: {}", comp_err.errors)
                }

                Ok(comp_state) => {
                    assert!(comp_state.functions.iter().any(|f| f.name == "normal"));

                    assert!(comp_state.templates.iter().any(|f| f.name == "add"));

                    assert!(!comp_state.functions.iter().any(|f| f.name == "add"));

                    assert!(!comp_state.templates.iter().any(|f| f.name == "normal"));
                }
            }
        })
    }

    #[test]
    fn test_compile_private_types() {
        run_test(|| {
            let result = compile(
                Source::build(Source::Memory {
                    name: String::from("private_types.rs"),
                    code: String::from(
                        r#"
                struct Unit;

                impl Drop for Unit {
                    fn drop(&mut self) {}
                }

                struct Private {
                    value: i32,
                }

                impl Private {
                    fn value(&self) -> i32 {
                        self.value
                    }
                }

                pub struct Public {
                    pub value: i32,
                }

                impl Public {
                    pub fn new() -> Self {
                        Public { value: Private { value: 1 }.value() }
                    }
                }

                pub fn unit() -> i32 {
                    let _unit = Unit;
                    1
                }
                "#,
                    ),
                }),
                &[],
            );

            match result {
                Err(comp_err) => assert!(false, "compilation failed: {}", comp_err.errors),
                Ok(comp_state) => {
                    // Only public structs are classes, implementations of other types are ignored
                    let names: Vec<&str> =
                        comp_state.classes.iter().map(|c| c.name.as_str()).collect();

                    assert_eq!(names, vec!["Public"]);
                }
            }
        })
    }
